'use strict';

const fs = require('node:fs');
const path = require('node:path');

function main() {
    const args = process.argv.slice(2);
    if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
        throw new Error('Usage: node scripts/sync-content.js [--check]');
    }

    const check = args[0] === '--check';
    const root = path.resolve(__dirname, '..');
    const contentDirectory = path.join(root, 'contents');
    const output = path.join(root, 'static', 'js', 'content-bundle.js');
    const filenames = fs.readdirSync(contentDirectory, { withFileTypes: true })
        .filter(entry => entry.isFile() && entry.name.endsWith('.md'))
        .map(entry => entry.name)
        .concat('config.yml')
        .sort();
    const content = Object.fromEntries(filenames.map(filename => [
        'contents/' + filename,
        fs.readFileSync(path.join(contentDirectory, filename), 'utf8').replace(/\r\n/g, '\n')
    ]));

    // Escape script-sensitive characters without changing the source strings.
    const serialized = JSON.stringify(content, null, 4)
        .replace(/</g, '\\u003c')
        .replace(/\u2028/g, '\\u2028')
        .replace(/\u2029/g, '\\u2029');
    const bundle = '// Generated by node scripts/sync-content.js. Do not edit directly.\n'
        + '// Source: contents/*.md and contents/config.yml.\n'
        + 'window.HOMEPAGE_CONTENT = ' + serialized + ';\n';

    let existing = null;
    try {
        existing = fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n');
    } catch (error) {
        if (error.code !== 'ENOENT') {
            throw error;
        }
    }

    if (check && existing !== bundle) {
        console.error('Content bundle is out of date. Run: node scripts/sync-content.js');
        process.exitCode = 1;
        return;
    }
    if (!check && existing !== bundle) {
        fs.mkdirSync(path.dirname(output), { recursive: true });
        fs.writeFileSync(output, bundle, 'utf8');
        console.log(`Updated static/js/content-bundle.js (${filenames.length} files).`);
        return;
    }
    console.log(`Content bundle is up to date (${filenames.length} files).`);
}

try {
    main();
} catch (error) {
    console.error(error.message);
    process.exitCode = 1;
}
